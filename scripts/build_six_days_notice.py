# -*- coding: utf-8 -*-
"""Generate src/pages/six-days-notice.astro from the book's own reportlab source.

The narrative, captions, timeline and sources are lifted verbatim from
build_book.py, the script that produced Six_Days_Notice.pdf, so the page and
the printed book cannot drift apart and no prose is ever retyped.

Usage:  python3 scripts/build_six_days_notice.py

Page styles live in scripts/six-days-notice.css and are inlined on generation;
edit that file, not the generated .astro.
"""
import ast, json, io, os

# The book's own reportlab source, vendored so the page is reproducible from
# this repo alone. Override with BOOKSRC to regenerate from an updated copy.
SRC = os.environ.get('BOOKSRC', 'scripts/six-days-notice.book.py')
OUT = 'src/pages/six-days-notice.astro'
CSS = 'scripts/six-days-notice.css'


def lit(node):
    try:
        return ast.literal_eval(node)
    except Exception:
        return None


def extract(path):
    """Walk the book script and pull its content blocks out in page order."""
    tree = ast.parse(io.open(path, encoding='utf-8').read())
    out = []
    for node in tree.body:
        line = node.lineno

        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            fn = getattr(node.value.func, 'id', None)
            args = [lit(a) for a in node.value.args]
            kw = {k.arg: lit(k.value) for k in node.value.keywords}

            if fn == 'text_page':
                out.append((line, {
                    'kind': 'text',
                    'kicker': args[0], 'title': args[1], 'dates': args[2],
                    'paragraphs': args[3],
                    'pull': kw.get('pull') or '',
                    'pullAttr': kw.get('pull_attr') or '',
                }))
            elif fn == 'plate_page':
                out.append((line, {
                    'kind': 'plate',
                    'band': args[0],
                    'panel': args[1].split('/')[-1].replace('.jpg', ''),
                    'caption': args[2],
                }))

        elif isinstance(node, ast.Assign) and getattr(node.targets[0], 'id', '') == 'events':
            out.append((line, {'kind': 'timeline',
                               'events': [list(e) for e in lit(node.value)]}))

        elif isinstance(node, ast.For) and isinstance(node.iter, ast.List):
            vals = lit(node.iter)
            if vals and isinstance(vals[0], str) and 'Plates.' in vals[0]:
                out.append((line, {'kind': 'sources', 'items': vals}))

    out.sort(key=lambda pair: pair[0])
    return [b for _, b in out]


sections = extract(SRC)
panels = sorted({s['panel'] for s in sections if s['kind'] == 'plate'})

TYPES = """type Section =
  | {
      kind: 'text';
      kicker: string;
      title: string;
      dates: string;
      paragraphs: string[];
      pull: string;
      pullAttr: string;
    }
  | { kind: 'plate'; band: string; panel: string; caption: string }
  | { kind: 'timeline'; events: string[][] }
  | { kind: 'sources'; items: string[] };"""

L = ["---",
     "// GENERATED by scripts/build_six_days_notice.py from the book's reportlab",
     "// source. Do not hand-edit the prose or the styles here; regenerate instead.",
     "import { Image } from 'astro:assets';",
     "import BaseLayout from '../layouts/BaseLayout.astro';"]
L += ["import %s from '../assets/six-days-notice/%s.jpg';" % (p, p) for p in panels]
L += ["",
      TYPES,
      "",
      "const sections: Section[] = " + json.dumps(sections, ensure_ascii=False, indent=2) + ";",
      "",
      "const panels: Record<string, ImageMetadata> = { %s };" % ', '.join(panels),
      "---",
      ""]

L.append('''<BaseLayout
  title="Six Days’ Notice"
  description="The Japanese Americans of Bainbridge Island, the war that took them, and the neighbors who kept their farms. A storybook of record, free to read and to download."
  type="article"
>
  <article class="book">
    <header class="masthead">
      <h1>Six Days&rsquo; Notice</h1>
      <p class="standfirst">
        The Japanese Americans of Bainbridge Island, the war that took them, and
        the neighbors who kept their farms.
      </p>
    </header>

    <section class="note">
      <p class="kicker">Why this exists</p>
      <p>
        I went to the memorial at Eagle Harbor. The story wall runs 276 feet, one
        foot for every name, and it slopes down toward the water.
      </p>
      <p>I was not prepared for it.</p>
      <p>
        227 people were taken from this island on March 30, 1942. Two thirds of
        them were American citizens. They were given six days. Bainbridge was
        first in the country, which means someone chose to begin here, and nobody
        stopped it.
      </p>
      <p>
        I made this book so the record would sit in one place. This is exactly the
        kind of thing a country forgets.
      </p>
    </section>

    <section class="epigraph">
      <blockquote>
        &ldquo;Let it not happen again that a group of people are singled out, that
        their loyalty and patriotism be questioned because of their race or
        ancestry.&rdquo;
      </blockquote>
      <p class="attr">Bainbridge Island Japanese American Exclusion Memorial</p>
    </section>

    {
      sections.map((s) =>
        s.kind === 'text' ? (
          <section class="chapter">
            <header class="chapter__head">
              <p class="kicker">{s.kicker}</p>
              <h2>{s.title}</h2>
              {s.dates && <p class="dates">{s.dates}</p>}
            </header>
            {s.paragraphs.map((t) => (
              <p class="body" set:html={t} />
            ))}
            {s.pull && (
              <blockquote class="pull">
                <p set:html={`&ldquo;${s.pull}&rdquo;`} />
                {s.pullAttr && <cite set:html={s.pullAttr} />}
              </blockquote>
            )}
          </section>
        ) : s.kind === 'plate' ? (
          <figure class="plate">
            <p class="plate__band">{s.band}</p>
            <div class="plate__mat">
              <Image
                src={panels[s.panel]}
                alt={s.caption.replace(/<[^>]+>/g, '')}
                widths={[480, 800, 1200]}
                sizes="(min-width: 800px) 760px, 100vw"
                loading="lazy"
              />
            </div>
            <figcaption set:html={s.caption} />
          </figure>
        ) : s.kind === 'timeline' ? (
          <section class="chapter timeline">
            <header class="chapter__head">
              <p class="kicker">The Record</p>
              <h2>Timeline</h2>
            </header>
            <dl>
              {s.events.map((e) => (
                <div class="timeline__row">
                  <dt set:html={e[0]} />
                  <dd set:html={e[1]} />
                </div>
              ))}
            </dl>
          </section>
        ) : (
          <section class="chapter sources">
            <header class="chapter__head">
              <p class="kicker">Credits</p>
              <h2>Sources &amp; Notes</h2>
            </header>
            {s.items.map((t) => (
              <p class="body" set:html={t} />
            ))}
          </section>
        )
      )
    }

    <p class="download">
      <a href="/six-days-notice.pdf" download>
        Also available as a printable book <span aria-hidden="true">&darr;</span>
      </a>
      <span class="download__meta">28 pages, letter size, PDF</span>
    </p>

    <footer class="colophon">
      <p class="colophon__motto">Nidoto Nai Yoni</p>
    </footer>
  </article>
</BaseLayout>
''')

css = io.open(CSS, encoding='utf-8').read().strip()
io.open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n' + css + '\n')
print('wrote %s  (%d sections, %d panels)' % (OUT, len(sections), len(panels)))
